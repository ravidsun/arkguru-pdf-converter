    ap = argparse.ArgumentParser()
    ap.add_argument("--python", required=True)
    ap.add_argument("--sink", choices=["file", "postgres"], required=True)
    ap.add_argument("--embedder", required=True)
    ap.add_argument("--model-name", required=True)
    ap.add_argument("--dim", type=int, required=True)
    ap.add_argument("--store", required=True)
    ap.add_argument("--corpus", required=True)
    ap.add_argument("--out-train", required=True)
    ap.add_argument("--skip-finetune", required=True)
    ap.add_argument("--input", action="append", default=[])
    args = ap.parse_args(argv)
    py = args.python

    if args.skip_finetune != "1":
        print("[wizard] Fine-tune is CLI-only (cd arkguru-rag-slm && make finetune); continuing with combine/index.", flush=True)
