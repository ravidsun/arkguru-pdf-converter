def _ollama_up() -> bool:
    try:
        import httpx

        r = httpx.get(f"{ollama_host()}/api/tags", timeout=2.0)
        return r.status_code < 500
    except Exception:
        return False


def chat(layout: Layout, req: ChatRequest) -> dict[str, Any]:
    phase3 = require(layout.phase3, "Phase 3 (arkguru-rag-slm)")
    if str(phase3) not in sys.path:
        sys.path.insert(0, str(phase3))
    if layout.common and str(layout.common) not in sys.path:
        sys.path.insert(0, str(layout.common))

    sink = req.sink or SESSION.sink or "file"
    embedder = req.embedder or SESSION.embedder or "hashing"
    store_path = Path(req.store or SESSION.store or default_store(layout))
    ollama = _ollama_up()
    model = req.model if (req.model and ollama) else None

    if sink == "postgres":
        answer, sources = _chat_postgres(req.question, embedder, req.dim, req.top_k, model)
        store_label = "postgres"
    else:
        answer, sources = _chat_file(
            req.question, embedder, store_path, req.top_k, model, req.dim
        )
        store_label = str(store_path)

    extractive = answer.strip().startswith("[extractive]") or not ollama or model is None
    return {
        "answer": answer,
        "sources": sources,
        "extractive": extractive,
        "ollama": ollama,
        "store": store_label,
        "embedder": embedder,
    }


def _chat_file(
    question: str,
    embedder: str,
    store_path: Path,
    top_k: int,
    model: str | None,
    dim: int,
) -> tuple[str, list[dict[str, Any]]]:
    from phase3_rag.embedder import Embedder
    from phase3_rag.vector_store import LocalVectorStore
    from phase3_rag import quickstart

    store = LocalVectorStore(str(store_path))
    if len(store) == 0:
        raise FileNotFoundError(
            f"Local vector store is empty at {store_path}. Run Phase 3 index first."
        )
    emb = Embedder(backend=embedder, dim=dim)
    hits = quickstart.retrieve(store, emb, question, top_k)
    answer = quickstart.answer(question, hits, model)
    return answer, [_source_from_hit(h) for h in hits]


def _chat_postgres(
    question: str,
    embedder: str,
    dim: int,
    top_k: int,
    model: str | None,
) -> tuple[str, list[dict[str, Any]]]:
    if not os.environ.get("PG_DSN"):
        raise RuntimeError("PG_DSN is not set")
    from common.datastore_config import open_chunk_store
    from phase3_rag.embedder import Embedder
    from phase3_rag import quickstart

    # Column order matches phase3_rag.run_pdfs._HIT (common.datastore search_*).
    cols = {
        "chunk_id": 0,
        "text": 1,
        "section": 2,
        "source_id": 3,
        "page": 4,
        "url": 5,
        "parent_id": 6,
        "chunk_index": 7,
        "title": 8,
        "lang": 9,
        "score": 10,
    }
    emb = Embedder(backend=embedder, dim=dim)
    store = open_chunk_store(dim=emb.dim)
    qvec = emb.encode([question])[0].tolist()
    rows = store.search_dense(qvec, k=top_k)
    hits: list[dict[str, Any]] = []
    for row in rows:
        hits.append(
            {
                "chunk_id": row[cols["chunk_id"]],
                "text": row[cols["text"]] or "",
                "section": row[cols["section"]],
                "source_id": row[cols["source_id"]],
                "page": row[cols["page"]],
                "url": row[cols["url"]],
                "parent_id": row[cols["parent_id"]],
                "chunk_index": row[cols["chunk_index"]],
            }
        )
    if not hits:
        return "No relevant context found.", []
    return quickstart.answer(question, hits, model), [_source_from_hit(h) for h in hits]


def _source_from_hit(hit: Any) -> dict[str, Any]:
    if isinstance(hit, dict):
        return {
            "chunk_id": hit.get("chunk_id"),
            "source_id": hit.get("source_id"),
            "page": hit.get("page"),
            "section": hit.get("section"),
            "url": hit.get("url"),
            "chunk_index": hit.get("chunk_index"),
            "text": (hit.get("text") or "")[:400],
        }
    return {
        "chunk_id": getattr(hit, "chunk_id", None),
        "source_id": getattr(hit, "source_id", None),
        "page": getattr(hit, "page", None),
        "section": getattr(hit, "section", None),
        "url": getattr(hit, "url", None),
        "chunk_index": getattr(hit, "chunk_index", None),
        "text": (getattr(hit, "text", "") or "")[:400],
    }
